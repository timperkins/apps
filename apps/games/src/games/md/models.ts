// Blocky models: every character is a handful of boxes in local space.
// f = forward, r = to the right, z = up; sizes are in tiles. All designs are original to M.D.
import type { MonsterKind, Trader } from './data';

export type Part = [f: number, r: number, z: number, sf: number, sr: number, sz: number, color: string, glow?: boolean];

export interface HeroLook {
  armor: string;
  trim: string;
  walk: number;
  moving: boolean;
}

const leg = (side: number, swing: number, color: string, z = 0, h = 0.34, w = 0.13): Part => [swing * side, side * 0.085, z, w, w, h, color];

export function heroParts(l: HeroLook): Part[] {
  const s = l.moving ? Math.sin(l.walk) * 0.09 : 0;
  return [
    leg(1, s, '#3a3a52'),
    leg(-1, s, '#3a3a52'),
    [s * 0.5, 0.085, 0, 0.15, 0.14, 0.06, '#4a2e1a'],
    [-s * 0.5, -0.085, 0, 0.15, 0.14, 0.06, '#4a2e1a'],
    [0, 0, 0.33, 0.22, 0.36, 0.38, l.armor],
    [0.005, 0, 0.36, 0.225, 0.365, 0.05, l.trim],
    [-0.12, 0, 0.42, 0.06, 0.28, 0.3, '#7a5a32'], // little backpack
    [-s, 0.24, 0.4, 0.12, 0.12, 0.32, l.armor],
    [s, -0.24, 0.4, 0.12, 0.12, 0.32, l.armor],
    [-s, 0.24, 0.36, 0.11, 0.11, 0.07, '#e8b890'],
    [s, -0.24, 0.36, 0.11, 0.11, 0.07, '#e8b890'],
    [0, 0, 0.71, 0.32, 0.32, 0.3, '#e8b890'],
    [-0.02, 0, 0.96, 0.35, 0.35, 0.1, '#6b3a1e'], // hair
    [-0.1, 0, 0.74, 0.16, 0.35, 0.24, '#6b3a1e'],
    [0.165, 0.075, 0.82, 0.02, 0.06, 0.06, '#20304a'],
    [0.165, -0.075, 0.82, 0.02, 0.06, 0.06, '#20304a'],
    [0.165, 0, 0.75, 0.02, 0.08, 0.025, '#b0684a'],
  ];
}

export function traderParts(t: Trader, bob: number): Part[] {
  const L = t.look;
  const p: Part[] = [
    [0, 0, 0, 0.3, 0.36, 0.62, L.robe],
    [0.005, 0, 0.3, 0.305, 0.365, 0.06, L.trim],
    [0, 0.23, 0.32, 0.12, 0.12, 0.28, L.robe],
    [0, -0.23, 0.32, 0.12, 0.12, 0.28, L.robe],
    [0.04, 0.23, 0.28, 0.1, 0.1, 0.06, L.skin],
    [0.04, -0.23, 0.28, 0.1, 0.1, 0.06, L.skin],
    [0, 0, 0.62 + bob, 0.32, 0.32, 0.3, L.skin],
    [0.165, 0.075, 0.74 + bob, 0.02, 0.06, 0.06, '#1a1a1a'],
    [0.165, -0.075, 0.74 + bob, 0.02, 0.06, 0.06, '#1a1a1a'],
    [0.165, 0, 0.66 + bob, 0.03, 0.14, 0.04, '#7a4a3a'], // smile / beard line
  ];
  if (t.id === 'smith') {
    p.push([0.16, 0, 0.05, 0.02, 0.3, 0.5, '#4a3020']); // leather apron
    p.push([0, 0, 0.9 + bob, 0.34, 0.34, 0.06, L.hat]); // bandana
    p.push([-0.2, 0, 0.86 + bob, 0.08, 0.1, 0.08, L.hat]);
    p.push([0.165, 0, 0.62 + bob, 0.04, 0.24, 0.07, '#5a3420']); // beard
  } else if (t.id === 'armorer') {
    p.push([0, 0, 0.9 + bob, 0.36, 0.36, 0.1, L.hat]); // steel cap
    p.push([0, 0, 1.0 + bob, 0.08, 0.08, 0.08, '#c8d0d8']);
    p.push([0.17, 0.15, 0.4, 0.04, 0.12, 0.14, '#9aa4ae']); // shoulder plates
    p.push([0.17, -0.15, 0.4, 0.04, 0.12, 0.14, '#9aa4ae']);
  } else {
    p.push([0, 0, 0.9 + bob, 0.38, 0.38, 0.05, L.hat]); // wide brim
    p.push([0, 0, 0.95 + bob, 0.22, 0.22, 0.14, L.hat]);
    p.push([0, 0, 1.09 + bob, 0.12, 0.12, 0.12, L.hat]);
    p.push([0, 0, 1.0 + bob, 0.225, 0.225, 0.03, '#f0c040']);
    p.push([-0.22, 0, 0.28, 0.16, 0.32, 0.36, '#8a5a2b']); // huge backpack
    p.push([-0.22, 0, 0.64, 0.12, 0.2, 0.08, '#b5483a']);
  }
  return p;
}

export function monsterParts(kind: MonsterKind, t: number, walk: number, state: string): Part[] {
  const s = Math.sin(walk) * 0.08;
  const wind = state === 'wind' || state === 'special';
  switch (kind) {
    case 'mossling': {
      const hop = Math.abs(Math.sin(walk * 0.8)) * 0.12;
      return [
        [0, 0, hop, 0.56, 0.56, 0.44, '#77806e'],
        [0, 0, 0.44 + hop, 0.58, 0.58, 0.08, '#5f9a3a'],
        [0.1, 0.12, 0.52 + hop, 0.14, 0.14, 0.08, '#86c450'],
        [-0.12, -0.1, 0.52 + hop, 0.16, 0.12, 0.1, '#4f8a30'],
        [0.285, 0.13, 0.24 + hop, 0.02, 0.1, 0.08, wind ? '#ff4030' : '#ffe24a', true],
        [0.285, -0.13, 0.24 + hop, 0.02, 0.1, 0.08, wind ? '#ff4030' : '#ffe24a', true],
        [0.285, 0, 0.1 + hop, 0.02, 0.24, 0.04, '#3a3f34'],
      ];
    }
    case 'lantern-monk': {
      const glow = wind ? '#fff6a0' : '#ffc94a';
      return [
        leg(1, s, '#2a1e30', 0, 0.22, 0.12),
        leg(-1, s, '#2a1e30', 0, 0.22, 0.12),
        [0, 0, 0.18, 0.32, 0.38, 0.42, '#4a2e52'],
        [0.17, 0, 0.18, 0.02, 0.12, 0.42, '#c9a040'],
        [0, 0.24, 0.36, 0.12, 0.12, 0.26, '#4a2e52'],
        [wind ? 0.12 : 0, -0.24, 0.36, 0.12, 0.12, 0.26, '#4a2e52'],
        [0, 0, 0.6, 0.36, 0.36, 0.36, '#2e1c34'], // hood
        [0.06, 0, 0.64, 0.26, 0.22, 0.24, glow, true], // the lantern inside
        [0.07, 0, 0.62, 0.27, 0.06, 0.28, '#3a2a18'],
        [0, 0, 0.96, 0.12, 0.12, 0.06, '#3a2a18'],
      ];
    }
    case 'sporecap': {
      const puff = wind ? 0.06 : 0;
      return [
        leg(1, s, '#c8bca0', 0, 0.14, 0.12),
        leg(-1, s, '#c8bca0', 0, 0.14, 0.12),
        [0, 0, 0.12, 0.34, 0.34, 0.38, '#efe6d0'],
        [0.175, 0.08, 0.32, 0.02, 0.06, 0.07, '#2a1a2a'],
        [0.175, -0.08, 0.32, 0.02, 0.06, 0.07, '#2a1a2a'],
        [0, 0, 0.5, 0.78 + puff, 0.78 + puff, 0.18, '#b02a6a'],
        [0, 0, 0.68, 0.56 + puff, 0.56 + puff, 0.12, '#c8387a'],
        [0.16, 0.2, 0.8, 0.12, 0.12, 0.04, '#fbe0f0'],
        [-0.18, 0.08, 0.8, 0.1, 0.1, 0.04, '#fbe0f0'],
        [0.04, -0.2, 0.8, 0.12, 0.12, 0.04, '#fbe0f0'],
        [0.3, -0.3, 0.68, 0.1, 0.1, 0.03, '#fbe0f0'],
      ];
    }
    case 'rustknight': {
      const arm = wind ? -0.25 : s;
      return [
        leg(1, s, '#6b4a3a', 0, 0.4, 0.18),
        leg(-1, s, '#6b4a3a', 0, 0.4, 0.18),
        [0, 0, 0.38, 0.4, 0.56, 0.5, '#8a5a3e'],
        [0.01, 0, 0.5, 0.41, 0.4, 0.12, '#6b3e2a'],
        [arm, 0.38, 0.44, 0.2, 0.2, 0.44, '#7a4e36'],
        [-s, -0.38, 0.44, 0.2, 0.2, 0.44, '#7a4e36'],
        [0, 0.38, 0.82, 0.26, 0.26, 0.12, '#9a6a4a'],
        [0, -0.38, 0.82, 0.26, 0.26, 0.12, '#9a6a4a'],
        [0, 0, 0.88, 0.38, 0.38, 0.36, '#7a4e36'], // helm
        [0.195, 0, 1.02, 0.02, 0.26, 0.05, wind ? '#ff5030' : '#ff9a40', true],
        [0, 0.22, 1.12, 0.1, 0.1, 0.18, '#d8c8a8'],
        [0, -0.22, 1.12, 0.1, 0.1, 0.18, '#d8c8a8'],
        [0, 0.27, 1.26, 0.08, 0.08, 0.1, '#d8c8a8'],
        [0, -0.27, 1.26, 0.08, 0.08, 0.1, '#d8c8a8'],
        [arm + 0.16, 0.38, 0.3, 0.26, 0.26, 0.26, '#4a4a52'], // mace head
      ];
    }
    case 'gloomwing': {
      const flap = Math.sin(t * 18) * 0.16;
      const z = 0.55 + Math.sin(t * 3) * 0.08;
      return [
        [0, 0, z, 0.36, 0.36, 0.32, '#3a2a4a'],
        [0.04, 0, z + 0.32, 0.12, 0.36, 0.08, '#2a1e38'],
        [0.185, 0.08, z + 0.16, 0.02, 0.07, 0.06, '#ff3a5a', true],
        [0.185, -0.08, z + 0.16, 0.02, 0.07, 0.06, '#ff3a5a', true],
        [0.185, 0, z + 0.04, 0.02, 0.14, 0.03, '#e8e0f0'],
        [0, 0.4, z + 0.14 + flap, 0.3, 0.4, 0.04, '#5a3a6e'],
        [0, -0.4, z + 0.14 + flap, 0.3, 0.4, 0.04, '#5a3a6e'],
        [0, 0.64, z + 0.1 + flap * 1.6, 0.18, 0.14, 0.04, '#4a2e5e'],
        [0, -0.64, z + 0.1 + flap * 1.6, 0.18, 0.14, 0.04, '#4a2e5e'],
      ];
    }
    case 'frost-wisp': {
      const z = 0.4 + Math.sin(t * 2.5) * 0.1;
      const p: Part[] = [
        [0, 0, z, 0.18, 0.18, 0.12, '#8fd0f0', true],
        [0, 0, z + 0.12, 0.36, 0.36, 0.26, '#bfefff', true],
        [0, 0, z + 0.38, 0.24, 0.24, 0.16, '#e6fbff', true],
        [0, 0, z + 0.54, 0.1, 0.1, 0.12, '#ffffff', true],
        [0.185, 0.07, z + 0.24, 0.02, 0.06, 0.06, wind ? '#ffffff' : '#2a5a8a'],
        [0.185, -0.07, z + 0.24, 0.02, 0.06, 0.06, wind ? '#ffffff' : '#2a5a8a'],
      ];
      for (let i = 0; i < 3; i++) {
        const a = t * 2 + (i * Math.PI * 2) / 3;
        p.push([Math.cos(a) * 0.42, Math.sin(a) * 0.42, z + 0.2 + Math.sin(a * 2) * 0.1, 0.09, 0.09, 0.12, '#aee8ff', true]);
      }
      return p;
    }
    case 'cinder-hound': {
      const lunge = wind ? 0.12 : 0;
      return [
        [0.18 + s, 0.12, 0, 0.1, 0.1, 0.26, '#3a2a26'],
        [0.18 - s, -0.12, 0, 0.1, 0.1, 0.26, '#3a2a26'],
        [-0.2 - s, 0.12, 0, 0.1, 0.1, 0.26, '#3a2a26'],
        [-0.2 + s, -0.12, 0, 0.1, 0.1, 0.26, '#3a2a26'],
        [0, 0, 0.24, 0.62, 0.34, 0.28, '#4a3430'],
        [0, 0, 0.52, 0.5, 0.2, 0.03, '#ff7a2a', true],
        [-0.05, 0.172, 0.3, 0.3, 0.02, 0.05, '#ff9a3a', true],
        [-0.05, -0.172, 0.3, 0.3, 0.02, 0.05, '#ff9a3a', true],
        [0.38 + lunge, 0, 0.36, 0.3, 0.3, 0.28, '#4a3430'],
        [0.55 + lunge, 0, 0.36, 0.08, 0.2, 0.12, '#2a1e1a'],
        [0.535 + lunge, 0.08, 0.52, 0.02, 0.06, 0.05, '#ffe066', true],
        [0.535 + lunge, -0.08, 0.52, 0.02, 0.06, 0.05, '#ffe066', true],
        [0.36 + lunge, 0.1, 0.64, 0.08, 0.06, 0.1, '#3a2a26'],
        [0.36 + lunge, -0.1, 0.64, 0.08, 0.06, 0.1, '#3a2a26'],
        [-0.38, 0, 0.44, 0.2, 0.08, 0.08, '#ff7a2a', true],
      ];
    }
    case 'hollow-crown': {
      const arm = wind ? -0.4 : s;
      const core = 0.5 + Math.sin(t * 4) * 0.5;
      return [
        leg(1, s * 1.5, '#1e1828', 0, 0.7, 0.36),
        leg(-1, s * 1.5, '#1e1828', 0, 0.7, 0.36),
        [s * 1.5, 0.19, 0, 0.36, 0.36, 0.7, '#1e1828'],
        [-s * 1.5, -0.19, 0, 0.36, 0.36, 0.7, '#1e1828'],
        [0, 0, 0.66, 0.8, 1.1, 0.9, '#2a2238'],
        [0.41, 0, 0.9, 0.02, 0.34, 0.34, core > 0.5 ? '#d8a8ff' : '#9b6ad6', true],
        [arm, 0.74, 0.66, 0.38, 0.38, 0.86, '#2a2238'],
        [-s, -0.74, 0.66, 0.38, 0.38, 0.86, '#2a2238'],
        [arm + 0.05, 0.74, 0.5, 0.46, 0.46, 0.3, '#1e1828'],
        [-s + 0.05, -0.74, 0.5, 0.46, 0.46, 0.3, '#1e1828'],
        [0, 0, 1.56, 0.64, 0.64, 0.56, '#2a2238'],
        [0.325, 0.14, 1.78, 0.02, 0.12, 0.08, '#e0b0ff', true],
        [0.325, -0.14, 1.78, 0.02, 0.12, 0.08, '#e0b0ff', true],
        [0, 0, 2.12, 0.7, 0.7, 0.1, '#e0b040'],
        [0.28, 0.28, 2.22, 0.12, 0.12, 0.2, '#f0c850'],
        [0.28, -0.28, 2.22, 0.12, 0.12, 0.2, '#f0c850'],
        [-0.28, 0.28, 2.22, 0.12, 0.12, 0.2, '#f0c850'],
        [-0.28, -0.28, 2.22, 0.12, 0.12, 0.2, '#f0c850'],
        [0.3, 0, 2.24, 0.06, 0.12, 0.12, '#ff4a6a', true],
      ];
    }
  }
}
